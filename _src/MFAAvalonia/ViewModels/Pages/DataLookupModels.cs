    // 所有极化刀种的1至5级使用相同的起始曲线。
    private static Dictionary<int, long> BuildKiwameCurve(params long[] reqExp)
    {
        var dict = new Dictionary<int, long>();
        long cum = 0;
        for (int i = 0; i < reqExp.Length && i < 100; i++)
        {
            if (reqExp[i] > 0) cum += reqExp[i];
            dict[i + 1] = cum;
        }

        // 每条原始曲线的第101项是从100级升至101级的经验。
        if (reqExp.Length > 100)
        {
            cum += reqExp[100];
            dict[101] = cum;

            for (int i = 0; i < PostLevel100RequiredExp.Length; i++)
            {
                cum += PostLevel100RequiredExp[i];
                dict[i + 102] = cum;
            }
        }

        // 确保等级1存在。
        if (!dict.ContainsKey(1)) dict[1] = 0;
        return dict;
    }

